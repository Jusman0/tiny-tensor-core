"""
Golden model for tiny-tensor-core: the TinyML MNIST network in integer-only
arithmetic, exactly as the RTL computes it.

  layer 1         acc1[j] = sum_i W1[j][i] * x[i]                      (int8 x int8)
  requantization  h[j]    = clamp((acc1[j] * M1 + B1q[j] + 2^(S-1)) >> S, 0, 127)
  layer 2         acc2[k] = sum_j W2[k][j] * h[j]
  argmax          digit   = argmax_k (acc2[k] + B2q[k])

M1, B1q and B2q replace the Arduino's float scales and biases:
  M1  = round(S1 / SH * 2^S)     one fixed-point multiplier for every neuron
  B1q = round(b1 / SH * 2^S)     layer-1 bias in the same fixed-point units
  B2q = round(b2 / S2)           layer-2 bias in accumulator units; scaling
                                 every logit by S2 > 0 can't change the argmax

Writes rom/ (weights, biases and params.vh; committed) and sim/ (test images
and expected values). Prints the integer path against the Arduino's float
path, emulated in NumPy, over all 10,000 MNIST test images (the UNO itself
ran only 5).

Run from the repo root:  python3 model/golden.py
"""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SHIFT = 24


def to_hex(v, bits):
    return f"{int(v) & ((1 << bits) - 1):0{bits // 4}x}"


def pack(values, bits):
    """values[0] in the lowest bits, so the hex string lists the last first."""
    return "".join(to_hex(v, bits) for v in reversed(list(values)))


def load():
    q = np.load(ROOT / "model" / "tinyml_weights_int8.npz")
    d = np.load(ROOT / "data" / "mnist_test_14x14.npz")
    return q, d["x"].astype(np.int64), d["labels"].astype(np.int64)


def integer_params(q):
    s1, sh, s2 = float(q["S1"]), float(q["SH"]), float(q["S2"])
    m1 = int(round(s1 / sh * 2 ** SHIFT))
    b1q = np.round(q["b1"].astype(np.float64) / sh * 2 ** SHIFT).astype(np.int64)
    b2q = np.round(q["b2"].astype(np.float64) / s2).astype(np.int64)
    return m1, b1q, b2q


def run_integer(x, w1, w2, m1, b1q, b2q):
    acc1 = x @ w1.T
    h = ((acc1 * m1 + b1q + (1 << (SHIFT - 1))) >> SHIFT).clip(0, 127)
    acc2 = h @ w2.T
    return h, acc2, (acc2 + b2q).argmax(1)


def run_float(x, q, w1, w2):
    """The Arduino's float path in NumPy: float rescale and bias between layers."""
    a1 = np.maximum((x @ w1.T) * np.float32(q["S1"]) + q["b1"], 0.0)
    h = np.round(a1 / np.float32(q["SH"])).clip(0, 127).astype(np.int64)
    logits = (h @ w2.T) * np.float32(q["S2"]) + q["b2"]
    return h, logits.argmax(1)


def write_rom(w1, w2, m1, b1q, b2q):
    rom = ROOT / "rom"
    rom.mkdir(exist_ok=True)
    # w1.hex: one line per input pixel i, holding W1[0..31][i] (lane j in byte j)
    (rom / "w1.hex").write_text("".join(pack(w1[:, i], 8) + "\n"
                                        for i in range(w1.shape[1])))
    (rom / "w2.hex").write_text("".join(pack(w2[:, j], 8) + "\n"
                                        for j in range(w2.shape[1])))
    (rom / "b1q.hex").write_text("".join(to_hex(v, 32) + "\n" for v in b1q))
    (rom / "b2q.hex").write_text("".join(to_hex(v, 32) + "\n" for v in b2q))
    (rom / "params.vh").write_text(
        "// generated by model/golden.py\n"
        f"localparam TC_SHIFT = {SHIFT};\n"
        f"localparam TC_M1    = {m1};   // round(S1 / SH * 2^{SHIFT})\n")


def write_sim(x, labels, h, acc2, pred):
    sim = ROOT / "sim"
    sim.mkdir(exist_ok=True)
    (sim / "images.hex").write_text("".join(f"{p:02x}\n" for p in x.ravel()))
    (sim / "labels.hex").write_text("".join(f"{v:02x}\n" for v in labels))
    (sim / "exp_h.hex").write_text("".join(pack(r, 8) + "\n" for r in h))
    (sim / "exp_acc2.hex").write_text("".join(pack(r, 24) + "\n" for r in acc2))
    (sim / "exp_pred.hex").write_text("".join(f"{v:02x}\n" for v in pred))


def main():
    q, x, labels = load()
    w1, w2 = q["W1q"].astype(np.int64), q["W2q"].astype(np.int64)
    m1, b1q, b2q = integer_params(q)

    h, acc2, pred = run_integer(x, w1, w2, m1, b1q, b2q)
    hf, pred_f = run_float(x, q, w1, w2)

    # worst case, not just this data, must fit 24 bits: 196*127*128 (layer 1), 32*127*128 (layer 2)
    assert 196 * 127 * 128 < 2 ** 23 and 32 * 127 * 128 < 2 ** 23
    assert 0 < m1 < 2 ** 16

    write_rom(w1, w2, m1, b1q, b2q)
    write_sim(x, labels, h, acc2, pred)

    n = len(labels)
    print(f"M1 = {m1}, shift = {SHIFT}")
    print(f"float path   (Arduino math, in NumPy): "
          f"{100 * (pred_f == labels).mean():.2f}% on {n} MNIST test images")
    print(f"integer path (RTL)                   : "
          f"{100 * (pred == labels).mean():.2f}%")
    print(f"hidden values that differ: {(h != hf).sum()} of {h.size} "
          f"(max difference {np.abs(h - hf).max()})")
    print(f"predictions that differ  : {(pred != pred_f).sum()} of {n}")


if __name__ == "__main__":
    main()
